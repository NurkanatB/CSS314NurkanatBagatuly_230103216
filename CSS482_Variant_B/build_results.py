"""Builds RESULTS_B.md from the JSON files written by the three experiment scripts,
so every number in the report is a real measurement from YOUR machine.
Run AFTER the three experiments:  python build_results.py"""
import json, os, sys
from bench_common import HERE, OUT_DIR

ALLOW_QUICK = "--allow-quick" in sys.argv


def load(name):
    path = os.path.join(OUT_DIR, name)
    if not os.path.exists(path):
        sys.exit(f"Missing {path} - run the experiment script first.")
    with open(path, encoding="utf-8") as f:
        d = json.load(f)
    if d.get("quick") and not ALLOW_QUICK:
        sys.exit(f"{name} came from a --quick smoke test. Re-run the script without --quick.")
    return d


def f(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def row(rows, p, cfg=None):
    return next(r for r in rows if r["p"] == p and (cfg is None or r["config"] == cfg))


a, b, c = load("exp_a_results.json"), load("exp_b_results.json"), load("exp_c_results.json")
env = a["env"]
cfgs = []
for r in a["rows"]:
    if r["config"] not in cfgs:
        cfgs.append(r["config"])
micro, coarse = cfgs[0], cfgs[1]
L = []
w = L.append

w("# RESULTS_B - Scalability Diagnostics: Granularity & IPC Contention\n")
w("All numbers below were measured by running the three scripts on the machine described in section A "
  "(generated by `build_results.py` from `outputs/*.json`). Nothing is hardcoded or copied from the handout.\n")
w("## A. Hardware and Software Configuration\n")
w("| Item | Value |\n|---|---|")
w(f"| Student ID | {env['student_id']} |")
w(f"| Python | {env['python']} |")
w(f"| Operating system | {env['os']} |")
w(f"| CPU | {env['cpu_name']} |")
w(f"| Logical CPUs (`os.cpu_count()`) | {env['os_cpu_count']} |")
w(f"| `multiprocessing.cpu_count()` | {env['mp_cpu_count']} |")
w(f"| Start method used | {env['start_method']} (available: {', '.join(env['available_start_methods'])}) |")
w("")
if env["os_cpu_count"] is not None and env["os_cpu_count"] < 8:
    w(f"> **Note:** only {env['os_cpu_count']} logical CPUs are available, so P=8 oversubscribes the machine. "
      "Speedups beyond that core count are physically impossible and e(8) is inflated by oversubscription.\n")

w("## B. Experiment A - Granularity Trap (1,000,000 Collatz items)\n")
w("| Configuration | P | Runtime (s) | Speedup | Efficiency (%) | Karp-Flatt |\n|---|---|---|---|---|---|")
for r in a["rows"]:
    w(f"| {r['config']} | {r['p']} | {f(r['time'])} | {f(r['speedup'],2)} | {f(r['efficiency'],1)} | {f(r['karp_flatt'])} |")
w(f"\nVerification (all runs gave the same step sum {a['sum']:,}): **{'PASS' if a['verified'] else 'FAIL'}**. "
  "Each chunk configuration uses its own P=1 baseline.\n")
m8, c8 = row(a["rows"], 8, micro), row(a["rows"], 8, coarse)
m1, c1 = row(a["rows"], 1, micro), row(a["rows"], 1, coarse)
w(f"**Measured:** at P=8 the micro-task run reached S={f(m8['speedup'],2)} (e={f(m8['karp_flatt'])}) while the coarse run reached "
  f"S={f(c8['speedup'],2)} (e={f(c8['karp_flatt'])}). Even at P=1, k=1 took {f(m1['time'],2)} s versus {f(c1['time'],2)} s for k=10,000 "
  f"({m1['time']/c1['time']:.2f}x), which isolates pure dispatch/pickling cost.\n")
w("**Why chunking helps.** With `chunksize=1`, `Pool.map` creates 1,000,000 task envelopes. Each is pickled by the master, pushed "
  "through a shared pipe, unpickled by a worker, and its result is pickled back. That per-task cost is comparable to or larger than the "
  "work (a Collatz walk is only ~100 loop iterations on average), and the master is a single serial dispatcher, so it becomes the bottleneck. "
  "With `chunksize=10,000` only 100 envelopes exist; each carries a block of numbers, so the fixed IPC cost is amortized over thousands of items "
  "and workers compute with almost no master involvement. Note that Collatz cost is uneven, so a few large chunks can also cause some load imbalance.\n")

w("## C. Experiment B - IPC Queue Choke-Point (400,000 items)\n")
w("| P | Runtime (s) | Speedup | Runtime vs T1 | Karp-Flatt |\n|---|---|---|---|---|")
for r in b["rows"]:
    w(f"| {r['p']} | {f(r['time'])} | {f(r['speedup'],2)} | {r['runtime_ratio']:.2f}x | {f(r['karp_flatt'])} |")
w(f"\nVerification (master collected exactly 400,000 items per P, checksums match): **{'PASS' if b['verified'] else 'FAIL'}**. "
  f"Runtime strictly monotonic in P: **{b['monotonic']}**.\n")
b1, b2, b8 = row(b["rows"], 1), row(b["rows"], 2), row(b["rows"], 8)
w(f"**Measured:** T1={f(b1['time'],2)} s, T8={f(b8['time'],2)} s (T8/T1 = {b8['runtime_ratio']:.2f}x); e(2)={f(b2['karp_flatt'],2)}, e(8)={f(b8['karp_flatt'],2)}.\n")
w("**Explanation.** `multiprocessing.Queue.put` appends to a buffer; a background feeder thread in each worker pickles the item and writes it "
  "to a shared OS pipe guarded by a cross-process write lock. With P producers all writing single tiny items, they fight over that lock "
  "(each acquisition is a syscall and potentially a context switch), while the master's single `get()` loop - which also takes a read lock, "
  "unpickles one item at a time - is a strictly serial consumer. Total useful work per item is trivial (`i % 7`), so the run time is almost entirely "
  "synchronization: adding processes adds lock contention, scheduler switches and cache-line ping-pong without adding consumption capacity. "
  "That is negative scaling: Tp grows with p and e(p) grows with p.\n")
w("**Expected vs observed.** The handout quotes illustrative values (e.g. T1~1.2 s, T8~7.6 s, e(8)~6.28). Absolute times depend on CPU, Windows scheduler and "
  "Python version, so they will differ. What should carry over is the *shape*: T increasing with P and e(p) rising. "
  + ("This run shows that shape.\n" if b["monotonic"] and b8["time"] > b1["time"] else
     "**This run did NOT show a strictly monotonic increase / T8 > T1**; the numbers above are reported as measured and the deviation should be attributed to this machine's behaviour (e.g. master consumer speed vs. producer speed, scheduler effects) rather than adjusted.\n"))

w("## D. Experiment C - Local Buffer Chunking (10,000,000 items, batch 10,000)\n")
w("| P | Runtime (s) | Speedup | Efficiency (%) | Karp-Flatt |\n|---|---|---|---|---|")
for r in c["rows"]:
    w(f"| {r['p']} | {f(r['time'])} | {f(r['speedup'],2)} | {f(r['efficiency'],1)} | {f(r['karp_flatt'],4)} |")
c1r, c2, c8r = row(c["rows"], 1), row(c["rows"], 2), row(c["rows"], 8)
w(f"\nVerification (totals equal closed-form expected sums): **{'PASS' if c['verified'] else 'FAIL'}**.\n")
w(f"**Throughput comparison.** Exp C processed 25x more items than Exp B. B's P=8 run handled {400000/b8['time']:,.0f} items/s; "
  f"C's P=8 run handled {10_000_000/c8r['time']:,.0f} items/s ({(10_000_000/c8r['time'])/(400000/b8['time']):.0f}x higher). "
  f"At P=1: B {400000/b1['time']:,.0f} items/s vs C {10_000_000/c1r['time']:,.0f} items/s.\n")
w("**Why aggregation helps.** Each worker now does its per-item work in a private Python list (no locks, no pipe). "
  "It crosses the IPC boundary once per 10,000 items, so the queue sees ~1/10,000th of the messages (about 1,000 puts in total instead of "
  "10,000,000 if unbuffered). Synchronization cost is amortized, the master's serial work becomes negligible, and the remaining runtime is "
  "genuinely parallel computation. Process start-up (spawn on Windows re-imports the module) is the main fixed cost left.\n")

def verdict_a(e8):
    if e8 is None: return "n/a"
    return "Flat/low e -> healthy scaling" if e8 < 0.1 else "High e -> dispatch/IPC overhead"

def verdict_b():
    return "IPC lock contention explosion" if b8["time"] > b1["time"] else "Contention present, no negative scaling on this machine"

def verdict_c():
    return "Amortized synchronization" if c8r["karp_flatt"] < 0.1 else "Overhead remains (see note)"

w("## E. Final Diagnostic Comparison\n")
w("| Configuration | T1 | T2 | T4 | T8 | S8 | e(2) | e(8) | Verdict |\n|---|---|---|---|---|---|---|---|---|")
for lab, cfg in (("A: Micro (k=1)", micro), ("A: Coarse Chunk (k=10,000)", coarse)):
    t = {p: row(a["rows"], p, cfg) for p in (1, 2, 4, 8)}
    w(f"| {lab} | {f(t[1]['time'],2)} | {f(t[2]['time'],2)} | {f(t[4]['time'],2)} | {f(t[8]['time'],2)} | {f(t[8]['speedup'],2)} | "
      f"{f(t[2]['karp_flatt'])} | {f(t[8]['karp_flatt'])} | {verdict_a(t[8]['karp_flatt'])} |")
t = {p: row(b["rows"], p) for p in (1, 2, 4, 8)}
w(f"| B: Queue Choke | {f(t[1]['time'],2)} | {f(t[2]['time'],2)} | {f(t[4]['time'],2)} | {f(t[8]['time'],2)} | {f(t[8]['speedup'],2)} | "
  f"{f(t[2]['karp_flatt'])} | {f(t[8]['karp_flatt'])} | {verdict_b()} |")
t = {p: row(c["rows"], p) for p in (1, 2, 4, 8)}
w(f"| C: Buffered Batch | {f(t[1]['time'],2)} | {f(t[2]['time'],2)} | {f(t[4]['time'],2)} | {f(t[8]['time'],2)} | {f(t[8]['speedup'],2)} | "
  f"{f(t[2]['karp_flatt'])} | {f(t[8]['karp_flatt'])} | {verdict_c()} |")
w("\nAll times in seconds. Workloads differ (A: 1M items, B: 400k, C: 10M), so compare shapes (S8, e(p)), not raw times.\n")
w("Handout targets for comparison (not measured here): B should show T8 > T1 and rising e(p); C should show S8 > 5 and e(8) <= 0.05. "
  f"Measured: B T8>T1 = {b8['time'] > b1['time']}; C S8 = {f(c8r['speedup'],2)}, e(8) = {f(c8r['karp_flatt'],4)}. "
  "Whether those targets are met is a property of this machine, and any miss is reported as measured.\n")

w("## F. Technical Discussion\n")
w("1. **Small tasks and scheduling overhead.** Every dispatched task costs a fixed amount of pickling, pipe I/O, wake-up and result return, paid by the master and a worker. "
  "If the work per task is comparable to that cost, the serial master saturates and workers idle (Experiment A, k=1).\n"
  "2. **Shared queues as bottlenecks.** A `Queue` is one pipe with locks and one reader. Producers serialize on the write lock and the consumer serializes on reads, so throughput is capped "
  "by a single channel and more producers only add contention (Experiment B).\n"
  "3. **Batching.** Aggregating locally replaces N messages by N/batch messages, so fixed per-message cost shrinks by the batch factor (Experiment C and Experiment A with k=10,000).\n"
  "4. **Karp-Flatt.** e(p) is the experimentally implied serial fraction. A flat e(p) across p=2,4,8 indicates a constant serial fraction (Amdahl-like); an e(p) that rises with p indicates overhead growing with the "
  "process count: lock waits, dispatch, IPC, oversubscription. Caveat: on a machine with fewer than 8 logical CPUs, oversubscription inflates e(8) in every experiment.\n"
  "5. **More workers is not always better.** Overhead can scale with p (contention, context switches, process start-up) and physical cores are finite; beyond the point where overhead growth exceeds the added compute, runtime rises.\n"
  "6. **Best optimization per experiment.** A: increase `chunksize` (or use `imap_unordered` with a sensible chunk). B: stop sending per-item messages - batch or aggregate in the worker. "
  "C: already near-optimal; remaining gains come from reducing process start-up or using a faster per-item loop, and from matching P to physical cores.\n")

w("## G. Conclusion\n")
w("**Measured:** see the tables above for the exact figures. Experiment A shows the cost of per-task dispatch and its removal by chunking; Experiment B isolates IPC cost by making work trivial and "
  "messages maximal; Experiment C removes that cost with local aggregation. "
  f"On this machine: A-micro S8={f(m8['speedup'],2)}, A-coarse S8={f(c8['speedup'],2)}, B S8={f(b8['speedup'],2)}, C S8={f(c8r['speedup'],2)}.\n")
w("**Theoretical expectation (not a measurement):** well-amortized CPU-bound work should scale close to the number of *physical* cores, with a small, flat e(p); communication-bound work "
  "should show e(p) that grows with p. Any difference between those expectations and the table is attributable to the hardware, the OS scheduler, SMT (logical vs physical cores) and the Python/spawn startup cost, "
  "and is reported here as observed rather than adjusted.\n")

path = os.path.join(HERE, "RESULTS_B.md")
with open(path, "w", encoding="utf-8") as fh:
    fh.write("\n".join(L) + "\n")
print("Wrote", path)
